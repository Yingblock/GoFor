// 构建前同步「构建期插件」注册表。
//
// 为什么需要：@gofor/plugins 的 index.ts 是静态 import，删掉一个 plugins/<name>
// 目录后构建会直接失败。这里扫描仍然存在的插件目录，重写：
//   - packages/plugins/src/index.ts 的 import + BUILTIN_PLUGINS 顺序
//   - packages/plugins/package.json 的 workspace 依赖
// 于是「删目录 → pnpm build」就能得到一个缺少该插件的可运行产物。
//
// 不引入依赖，只读写本仓库；不改各插件自己的 package.json。
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const PLUGINS_DIR = join(ROOT, 'plugins');
const AGGREGATOR_DIR = join(ROOT, 'packages', 'plugins');
const INDEX_PATH = join(AGGREGATOR_DIR, 'src', 'index.ts');
const PACKAGE_PATH = join(AGGREGATOR_DIR, 'package.json');

/** 原 BUILTIN_PLUGINS 的顺序；未知目录按字母序追加，保证构建可复现。 */
const KNOWN_ORDER = [
  'pomodoro',
  'tasks',
  'timetable',
  'checkin',
  'scan',
  'checklist',
  'mood',
  'report',
  'diary',
  'toolbox',
  'wordbook',
  'theme',
  'converter',
];

function discoverPlugins() {
  if (!existsSync(PLUGINS_DIR)) return [];
  const found = [];
  for (const entry of readdirSync(PLUGINS_DIR, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const dir = join(PLUGINS_DIR, entry.name);
    const packagePath = join(dir, 'package.json');
    const indexPath = join(dir, 'src', 'index.ts');
    if (!existsSync(packagePath) || !existsSync(indexPath)) continue;

    const packageJson = JSON.parse(readFileSync(packagePath, 'utf8'));
    if (typeof packageJson.name !== 'string') {
      throw new Error(`plugins/${entry.name}/package.json 缺少 name`);
    }
    const source = readFileSync(indexPath, 'utf8');
    const match = source.match(/export\s+const\s+([A-Za-z_$][\w$]*Plugin)\b/);
    if (!match) {
      throw new Error(`plugins/${entry.name}/src/index.ts 找不到 export const *Plugin`);
    }
    found.push({
      dir: entry.name,
      packageName: packageJson.name,
      exportName: match[1],
    });
  }

  const byDir = new Map(found.map((plugin) => [plugin.dir, plugin]));
  const ordered = [];
  for (const dir of KNOWN_ORDER) {
    const plugin = byDir.get(dir);
    if (plugin) {
      ordered.push(plugin);
      byDir.delete(dir);
    }
  }
  ordered.push(...[...byDir.values()].sort((a, b) => a.dir.localeCompare(b.dir)));
  return ordered;
}

function writeIndex(plugins) {
  const imports = plugins
    .map((plugin) => `import { ${plugin.exportName} } from '${plugin.packageName}';`)
    .join('\n');
  const entries = plugins.map((plugin) => `  ${plugin.exportName},`).join('\n');
  const content = `// AUTO-GENERATED by tools/sync-plugin-registry.mjs — 不要手改。
// 删掉 plugins/<name> 后运行 \`pnpm build\` 会重新生成，产物就少了这个插件。
import type { PluginModule } from '@gofor/plugin-api';
${imports}

/**
 * 当前存在的构建期插件。顺序决定：
 * - 依赖解析之外的稳定激活顺序；
 * - 多个主题包同时启用时哪个生效（第一个）；
 * - 安装页的展示顺序。
 */
export const BUILTIN_PLUGINS: readonly PluginModule[] = [
${entries}
];

/**
 * 默认关闭的内置插件。
 *
 * 主题包是唯一一个：它一启用就改整站外观，应该是用户主动选择的，
 * 不能"装好就变样"。其它内置插件（清单/周报/单词库…）默认开启，
 * 否则升级后用户会发现功能"消失"。
 */
const DEFAULT_DISABLED = new Set(['gofor.theme.sepia']);

export function isBuiltinEnabledByDefault(id: string): boolean {
  return !DEFAULT_DISABLED.has(id);
}

/** 内置插件的 manifest JSON（播种进 \`plugins\` 表用）。 */
export function builtinManifestJson(plugin: PluginModule): string {
  return JSON.stringify(plugin.manifest);
}
`;
  writeFileSync(INDEX_PATH, content);
}

function writePackage(plugins) {
  const packageJson = JSON.parse(readFileSync(PACKAGE_PATH, 'utf8'));
  const dependencies = {};
  for (const plugin of plugins) dependencies[plugin.packageName] = 'workspace:*';
  dependencies['@gofor/plugin-api'] = 'workspace:*';
  packageJson.dependencies = Object.fromEntries(
    Object.entries(dependencies).sort(([a], [b]) => a.localeCompare(b)),
  );
  writeFileSync(PACKAGE_PATH, `${JSON.stringify(packageJson, null, 2)}\n`);
}

const plugins = discoverPlugins();
writeIndex(plugins);
writePackage(plugins);
console.log(
  `[plugin-sync] ${plugins.length} 个插件：${plugins.map((plugin) => plugin.dir).join(', ') || '（无）'}`,
);
